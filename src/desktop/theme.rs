//! Semantic colors derived from the document window's system appearance.
use gpui::{Window, WindowAppearance};

#[derive(Clone, Copy)]
pub struct Theme {
    pub window: u32,
    pub toolbar: u32,
    pub content: u32,
    pub text: u32,
    pub secondary: u32,
    pub separator: u32,
    pub control: u32,
    pub control_hover: u32,
    pub accent: u32,
    pub live: u32,
    pub warning: u32,
    pub canvas: u32,
    pub canvas_alt: u32,
    pub grid: u32,
    pub octave_grid: u32,
    pub key: u32,
    pub black_key: u32,
    pub note: u32,
    pub note_text: u32,
    pub candidate: u32,
    pub cursor: u32,
    pub waveform: u32,
}
impl Theme {
    pub fn for_window(window: &Window) -> Self {
        match window.appearance() {
            WindowAppearance::Dark | WindowAppearance::VibrantDark => Self {
                window: 0x242426,
                toolbar: 0x2a2a2d,
                content: 0x202023,
                text: 0xf2f2f7,
                secondary: 0xa5a5ab,
                separator: 0x414146,
                control: 0x3a3a3f,
                control_hover: 0x48484d,
                accent: 0x0a84ff,
                live: 0xff9f0a,
                warning: 0xffb340,
                canvas: 0x191a1d,
                canvas_alt: 0x202126,
                grid: 0x2a2c32,
                octave_grid: 0x3a3d45,
                key: 0x292b30,
                black_key: 0x15161a,
                note: 0x285a90,
                note_text: 0xe4f0ff,
                candidate: 0x474d58,
                cursor: 0xe6e6eb,
                waveform: 0x7b8ca2,
            },
            WindowAppearance::Light | WindowAppearance::VibrantLight => Self {
                window: 0xf2f2f4,
                toolbar: 0xf7f7f8,
                content: 0xffffff,
                text: 0x1d1d1f,
                secondary: 0x6e6e73,
                separator: 0xd5d5da,
                control: 0xffffff,
                control_hover: 0xececf0,
                accent: 0x007aff,
                live: 0xc76c09,
                warning: 0x9a6700,
                canvas: 0xffffff,
                canvas_alt: 0xf6f7f9,
                grid: 0xe8eaf0,
                octave_grid: 0xd2d7e0,
                key: 0xf0f1f4,
                black_key: 0xe0e3e9,
                note: 0xbdd8fc,
                note_text: 0x154f90,
                candidate: 0xdce1e9,
                cursor: 0x4b4b52,
                waveform: 0x94a3b7,
            },
        }
    }
}
